export type WordCategory = 'SCOUT' | 'ASSAULT' | 'TANK' | 'BOSS' | 'SHORT' | 'MEDIUM' | 'LONG';

export function getRandomWord(type: WordCategory, usedWords: Set<string> = new Set()): string {
  let pool = WORDS_SHORT;
  if (type === 'ASSAULT' || type === 'MEDIUM') pool = WORDS_MEDIUM;
  if (type === 'TANK' || type === 'LONG' || type === 'BOSS') pool = WORDS_LONG;

  const available = pool.filter(w => !usedWords.has(w));
  const candidatePool = available.length > 0 ? available : pool;
  const randomIndex = Math.floor(Math.random() * candidatePool.length);
  return candidatePool[randomIndex];
}
